import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')

test('agents page, footer, and FAQ advertise the API without moving it onto the home page', () => {
  const agents = read('app/pages/agents.vue')
  const footer = read('app/components/SiteFooter.vue')
  const faq = read('app/pages/faq.vue')
  const home = read('app/pages/index.vue')
  const studio = read('app/components/StudioCreationPanel.vue')
  assert.match(agents, /SiteFooter/)
  assert.match(agents, /Free · No API key · No account/)
  assert.match(agents, /POST \/api\/v1\/storyboard/)
  assert.match(agents, /\/openapi\.json/)
  assert.match(agents, /\/mcp/)
  assert.match(agents, /Copy prompt for your AI/)
  assert.match(agents, /5 scenes × 3 seconds/)
  assert.match(agents, /scenes/)
  assert.doesNotMatch(agents, /not affiliated with/)
  assert.match(footer, /pageHref\('agents'\)/)
  assert.match(footer, />Agents</)
  assert.match(footer, /not affiliated with/)
  assert.doesNotMatch(footer, /\/developers|For AI agents|agent-links|llms\.txt/)
  assert.match(faq, /\/agents/)
  assert.match(read('public/faq.md'), /\/agents/)
  assert.doesNotMatch(home, /\/openapi\.json|\/api\/v1\/storyboard/)
  assert.match(studio, /Step-by-step storyboard/)
  assert.match(studio, /Copy share link/)
  assert.match(studio, /Download Markdown/)
  assert.match(studio, /studio-tips/)
  assert.match(studio, /9:16 for vertical, 16:9 for wide/)
  assert.match(studio, /watercolor or 35mm/)
  assert.match(studio, /tipsOpen = ref\(false\)/)
  assert.match(studio, /stepByStep = ref\(false\)/)
  assert.match(studio, /activePreset = ref\('15s'\)/)
  assert.match(read('app/components/StudioStepBuilder.vue'), /\+ Add scene/)
})

test('discovery files describe MCP, OpenAPI, the default board, and custom scenes', () => {
  assert.equal(read('AGENTS.md'), read('public/agents.md'))
  for (const file of ['AGENTS.md', 'README.md', 'public/llms.txt', 'public/llms-full.txt', 'public/index.md', 'public/product.md']) {
    const text = read(file)
    assert.match(text, /5 scenes/, file)
    assert.match(text, /scenes/, file)
    assert.match(text, /\/mcp|\/api\/v1\/storyboard/, file)
  }
  assert.match(read('AGENTS.md'), /"scenes"/)
  assert.match(read('AGENTS.md'), /Minified JSON/)
  assert.match(read('AGENTS.md'), /premise` may be omitted/)
  assert.match(read('app/pages/agents.vue'), /Minified JSON/)
  assert.match(read('public/llms.txt'), /Minified JSON/)
  assert.match(read('public/llms-full.txt'), /Minified JSON/)
  assert.match(read('README.md'), /"scenes"/)
  const discovery = JSON.parse(read('public/.well-known/mcp.json'))
  assert.equal(discovery.transport.url, 'https://moovicut.studio/mcp')
  assert.equal(discovery.authentication.type, 'none')
  assert.equal(discovery.defaults.shots, 5)
  assert.equal(discovery.defaults.duration, 3)
  assert.deepEqual(discovery.tools.map(tool => tool.name), ['plan_storyboard', 'export_prompts', 'validate_storyboard'])
  assert.match(read('public/sitemap.xml'), /https:\/\/moovicut\.studio\/agents/)
  assert.match(read('nuxt.config.ts'), /\/agents/)
})
